#!/usr/bin/env node
/**
 * Writes lib/follow-up-action-names.ts from the locales: every language's
 * text of each built-in follow-up action (`follow_up.actions.*`) and of a
 * mail without a subject (`follow_up.no_subject`), so a follow-up written in
 * one language is read back in another. The app cannot load every locale's
 * messages at run time, so they are kept in that file.
 *
 *   node scripts/follow-up-actions/generate.mjs
 *
 * Run it after a locale's follow-up actions change; a test fails while the
 * file is out of date.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const OUTPUT = join(ROOT, 'lib/follow-up-action-names.ts');

/** The file's text from the locales under `root`, in the order of `en`'s actions. */
export function renderFollowUpActionNames(root = ROOT) {
  const dir = join(root, 'locales');
  const locales = readdirSync(dir).sort();
  const followUp = locales.map((locale) => JSON.parse(readFileSync(join(dir, locale, 'common.json'), 'utf8')).follow_up ?? {});
  const english = followUp[locales.indexOf('en')];
  const keys = Object.keys(english.actions);
  const texts = (pick) => [...new Set(followUp.map(pick).filter((text) => typeof text === 'string' && text.trim()))];
  const list = (values) => `[${values.map((v) => JSON.stringify(v)).join(', ')}]`;
  return [
    '// Generated by scripts/follow-up-actions/generate.mjs from locales/*/common.json: do not edit.',
    '/**',
    ' * The built-in actions\' and the subject-less title\'s texts in every locale',
    ' * (`follow_up.actions.*`, `follow_up.no_subject`), so a follow-up written in',
    ' * one language is read back in another: its default action stays the',
    ' * default, a built-in one is shown in the current language.',
    ' */',
    'import type { FollowUpActionKey } from "./follow-up-actions";',
    '',
    'export const FOLLOW_UP_ACTION_NAMES: Record<FollowUpActionKey, readonly string[]> = {',
    ...keys.map((key) => `  ${key}: ${list(texts((f) => f.actions?.[key]))},`),
    '};',
    '',
    `export const FOLLOW_UP_NO_SUBJECT: readonly string[] = ${list(texts((f) => f.no_subject))};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, renderFollowUpActionNames());
  console.log(`wrote ${OUTPUT}`);
}
